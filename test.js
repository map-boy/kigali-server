const WebSocket = require('ws');
const url = process.argv[2] || 'ws://127.0.0.1:8080';
let bad = 0;
const ok = (c, m) => { console.log((c ? 'ok    ' : 'FAIL  ') + m); if (!c) bad++; };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const a = new WebSocket(url);
const b = new WebSocket(url);
const ga = [];
const gb = [];
a.on('message', (d) => ga.push(JSON.parse(d.toString())));
b.on('message', (d) => gb.push(JSON.parse(d.toString())));
(async () => {
  await Promise.all([new Promise((r) => a.on('open', r)), new Promise((r) => b.on('open', r))]);
  a.send(JSON.stringify({ t: 'create', track: 1 }));
  await wait(300);
  const c = ga.find((m) => m.t === 'created');
  ok(c && c.code.length === 4 && c.seat === 0 && c.track === 1, 'create room');
  b.send(JSON.stringify({ t: 'join', code: c ? c.code.toLowerCase() : 'XXXX' }));
  await wait(300);
  ok(gb.some((m) => m.t === 'joined' && m.seat === 1), 'join room (code is case-insensitive)');
  ok(ga.some((m) => m.t === 'start') && gb.some((m) => m.t === 'start'), 'both players get start');
  a.send(JSON.stringify({ t: 's', x: 1, y: 2 }));
  b.send(JSON.stringify({ t: 'fin', time: 61.5 }));
  await wait(300);
  ok(gb.some((m) => m.t === 's' && m.x === 1), 'state relayed a to b');
  ok(ga.some((m) => m.t === 'fin' && m.time === 61.5), 'finish relayed b to a');
  a.send(JSON.stringify({ t: 'again' }));
  await wait(200);
  ok(gb.some((m) => m.t === 'again'), 'rematch request reaches the friend');
  gb.length = 0;
  ga.length = 0;
  b.send(JSON.stringify({ t: 'again' }));
  await wait(300);
  ok(ga.some((m) => m.t === 'start') && gb.some((m) => m.t === 'start'), 'rematch starts when both agree');
  const x = new WebSocket(url);
  const gx = [];
  x.on('message', (d) => gx.push(JSON.parse(d.toString())));
  await new Promise((r) => x.on('open', r));
  x.send(JSON.stringify({ t: 'join', code: c ? c.code : 'XXXX' }));
  await wait(300);
  ok(gx.some((m) => m.t === 'error' && m.msg === 'room is full'), 'third player is refused');
  x.send(JSON.stringify({ t: 'join', code: 'ZZZZ' }));
  await wait(300);
  ok(gx.some((m) => m.t === 'error' && m.msg === 'no such room'), 'unknown code is refused');
  b.close();
  await wait(300);
  ok(ga.some((m) => m.t === 'left'), 'friend is told when the other leaves');
  console.log(bad ? 'FAILED ' + bad : 'all server tests ok');
  process.exit(bad ? 1 : 0);
})();